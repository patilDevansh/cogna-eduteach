// Records every line the Cogna guide (the orb) can say, in Cartesia "kiara",
// into audio/guide-kiara/<hash>.mp3, and writes audio/guide-manifest.js.
// The lines come from guide/script.js (allLines()), filled in for every student and day.
// Hash and spoken-text rules match tools/record-narration.mjs, so the app's voice player
// (screens/session.js) finds these recordings by the line's text.
// Only new or changed lines are recorded. Run from the repo root:
//   node prototypes/school-pilot-student-trail/tools/record-guide.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO = path.resolve(ROOT, "../..");
const env = Object.fromEntries(
  fs.readFileSync(path.join(REPO, ".env"), "utf8").split("\n")
    .map((l) => l.match(/^([A-Z0-9_]+)=(.*)$/)).filter(Boolean)
    .map((m) => [m[1], m[2].trim().replace(/^["']|["']$/g, "")]),
);
const KEY = env.CARTESIA_API_KEY;
if (!KEY) throw new Error("CARTESIA_API_KEY missing in .env");
const KIARA = "f8f5f1b2-f02d-4d8e-a40d-fd850a487b3d";

/** Must match narrationKey() in screens/session.js */
function hash(s) { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; return h.toString(36); }
/** Must match spoken() in tools/record-narration.mjs */
function spoken(t) {
  return t
    .replace(/\b([bch])\b/g, (m, l) => l.toUpperCase())
    .replace(/(^|[\s(+=×−])a(?=\s*(?:²|[+=×−)]|[.,]|$))/g, "$1A")
    .replace(/\ba(?= and B\b| is \d| = )/g, "A")
    .replace(/\bside a\b/g, "side A")
    .replace(/ \+ /g, " plus ").replace(/²/g, " square").replace(/√/g, "the square root of ")
    .replace(/−/g, " minus ").replace(/×/g, " times ").replace(/=/g, " equals ").replace(/½/g, "half");
}

// Load the prototype's data and the guide script, exactly as the browser does.
const ctx = { window: { Cogna: { data: {} } } };
vm.createContext(ctx);
for (const f of ["data/fig.js", "data/skills.js", "data/students.js", "data/days.js", "guide/script.js"]) {
  vm.runInContext(fs.readFileSync(path.join(ROOT, f), "utf8"), ctx, { filename: f });
}
const lines = ctx.window.Cogna.guideScript.allLines();

async function kiara(text) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch("https://api.cartesia.ai/tts/bytes", {
      method: "POST",
      headers: { "Content-Type": "application/json", "Cartesia-Version": "2026-08-14", Authorization: `Bearer ${KEY}` },
      body: JSON.stringify({
        model_id: env.CARTESIA_MODEL || "sonic-3.6", transcript: text, language: "en",
        voice: { mode: "id", id: KIARA },
        output_format: { container: "mp3", sample_rate: 44100, bit_rate: 128000 },
      }),
    });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    if (res.status === 429 && attempt < 4) { await new Promise((r) => setTimeout(r, 15000 * (attempt + 1))); continue; }
    throw new Error(`${res.status} ${(await res.text()).slice(0, 300)}`);
  }
}

const outDir = path.join(ROOT, "audio", "guide-kiara");
fs.mkdirSync(outDir, { recursive: true });
const map = {};
let made = 0;
for (const line of lines) {
  const k = hash(line), file = path.join(outDir, `${k}.mp3`);
  if (!fs.existsSync(file)) { fs.writeFileSync(file, await kiara(spoken(line))); made++; process.stdout.write("."); }
  map[k] = `audio/guide-kiara/${k}.mp3`;
}
fs.writeFileSync(path.join(ROOT, "audio", "guide-manifest.js"),
  "/* Generated by tools/record-guide.mjs — the Cogna guide's lines (Cartesia, voice kiara). */\n" +
  `window.Cogna.guideNarration = ${JSON.stringify(map)};\n`);
console.log(`\n${lines.length} lines, ${made} recorded now`);
